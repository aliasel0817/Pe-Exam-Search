'use strict';
const assert=require('node:assert/strict');
const c=require('./study-notification-core.js');
const settings={...c.DEFAULTS,enabled:true,planId:'synthetic-three-rounds'};
const now=Date.parse('2026-11-27T08:30:00+09:00');
const plan={id:settings.planId,rounds:3,verified:true,activeRevision:1,activeHash:'a'.repeat(64),days:[{date:'2026-11-27',round:1,ids:['T0001','T0002','T0003']}]};
const input={settings,now,ownerId:'synthetic',plan,records:[],claimedSlotKeys:[]};
assert.equal(c.slotAt(now-60000,5).inWindow,false);
assert.equal(c.slotAt(now,5).total,138);
assert.equal(c.slotAt(Date.parse('2026-11-27T20:00:00+09:00'),5).inWindow,false);
assert.equal(c.proposeSlot({...input,plan:null}).reason,'plan-unavailable');
assert.equal(c.proposeSlot({...input,plan:{...plan,verified:false}}).reason,'plan-unavailable');
assert.equal(c.proposeSlot({...input,plan:{...plan,rounds:5}}).reason,'plan-unavailable');
assert.equal(c.proposeSlot({...input,settings:{...settings,enabled:false}}).reason,'disabled');
const result=c.proposeSlot(input);
assert.equal(result.candidates[0].topicId,'T0001');
assert.equal(c.proposeSlot({...input,claimedSlotKeys:[result.slotKey]}).reason,'slot-already-claimed');
assert.equal(c.proposeSlot({...input,records:[{...result.candidates[0],status:'unknown'}]}).candidates[0].topicId,'T0002');
assert.equal(c.proposeSlot({...input,records:[{...result.candidates[0],date:'2026-11-26',status:'confirmed'}]}).candidates[0].topicId,'T0002');
assert.equal(c.proposeSlot({...input,records:[{...result.candidates[0],date:'2026-11-26',round:2}]}).candidates[0].topicId,'T0001');
assert.equal(c.proposeSlot({...input,plan:{...plan,days:[{...plan.days[0],ids:['T0001','T0001']}]}}).reason,'invalid-schedule');
const topic={topicId:'T0001',topicName:'Synthetic',concept:'가😀'.repeat(400),keywords:'test',mnemonic:'example'};
const p=c.prepareTopic(topic,settings);
assert.equal(p.parts.map(x=>x.text).join(''),p.body);
assert.ok(p.parts.every(x=>x.message.length<=200));
assert.ok(p.body.includes(topic.concept));
assert.ok(!p.body.includes('[특징]'));
assert.equal(c.classifyKakaoOutcome(200,{result_code:0}),'confirmed');
assert.equal(c.classifyKakaoOutcome(503,{}),'unknown');
assert.equal(c.classifyKakaoOutcome(400,{code:-2}),'rejected');
assert.throws(()=>c.cleanSettings({...settings,fields:['made-up']}));
console.log('PASS: isolated notification core assertions');

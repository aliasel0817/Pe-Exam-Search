const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const path = require('node:path');
const html = fs.readFileSync(path.join(__dirname, '..', 'study-note.html'), 'utf8');
const cacheStart = html.indexOf('const ATTACHMENT_PDF_CACHE_MAX_BYTES');
const cacheEnd = html.indexOf('let activeAttachmentPdfDocument', cacheStart);
const signatureStart = html.indexOf('function imageMediaSignature(');
const signatureEnd = html.indexOf('function evictCachedImageBlob', signatureStart);
assert(cacheStart >= 0 && cacheEnd > cacheStart && signatureEnd > signatureStart);
const context = vm.createContext({ AbortController });
vm.runInContext(html.slice(cacheStart, cacheEnd) + '\n' + html.slice(signatureStart, signatureEnd), context);
const call = (code) => vm.runInContext(code, context);
const item = {attachmentId:'a',driveFileId:'f',size:5,createdAt:'v1',mime:'application/pdf',fileName:'one.pdf'};
context.item = item;
context.bytes = new Uint8Array([37,80,68,70,45]);
call('saveCachedAttachmentPdfBytes(item, bytes, attachmentPdfCacheEpoch)');
assert.equal(call('getCachedAttachmentPdfBytes(item).length'),5);
context.bytes[0] = 1;
assert.equal(call('getCachedAttachmentPdfBytes(item)[0]'),37,'cache must copy input bytes');
const returned = call('getCachedAttachmentPdfBytes(item)');
returned[0] = 2;
assert.equal(call('getCachedAttachmentPdfBytes(item)[0]'),37,'viewer transfer must not mutate cached bytes');
context.item = {...item, size:6};
assert.equal(call('getCachedAttachmentPdfBytes(item)'),null,'metadata change must invalidate cache');
context.item = item;
context.bytes = new Uint8Array([37,80,68,70,45]);
call('saveCachedAttachmentPdfBytes(item, bytes, attachmentPdfCacheEpoch)');
call('clearCachedAttachmentPdfBytes()');
assert.equal(call('getCachedAttachmentPdfBytes(item)'),null,'security session cleanup clears cache');
assert(html.includes('attachmentPdfFetchAbort?.abort()'));
assert(html.includes('renderActiveAttachmentPdfCanvas({ preserveCenter: false, scheduleRender: false })'));
assert(html.includes('if (scheduleRender) repaintAttachmentPdfAtZoom()'));
assert(html.includes('fetchMediaContent(getApiUrl(), item.attachmentId, { signal: fetchAbort.signal })'));
assert.equal(call('attachmentPdfBytesCacheTotal'),0);
const scriptBlockStart = html.lastIndexOf('<script>', html.indexOf('async function fetchMediaContent('));
const scriptBlockEnd = html.indexOf('</script>', scriptBlockStart);
assert(scriptBlockStart >= 0 && scriptBlockEnd > scriptBlockStart);
new vm.Script(html.slice(scriptBlockStart + 8, scriptBlockEnd));
console.log('PASS attachment cache copy, invalidation, session purge, fetch abort, first paint and inline syntax');
